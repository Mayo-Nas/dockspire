# Regenerate bundled third-party attribution from the Linux import graphs.
[CmdletBinding()]
param([string]$Go = 'go', [switch]$Check)
$ErrorActionPreference = 'Stop'
$taskRoot = Split-Path -Parent $PSScriptRoot
$taskUTF8 = [Text.UTF8Encoding]::new($false)
$taskPattern = '^(LICENSE|LICENCE|COPYING|NOTICE|PATENTS)([.-].*)?$'

function Invoke-Go([string[]]$Arguments) {
    $taskLines = & $Go @Arguments
    if ($LASTEXITCODE -ne 0) { throw "Go command failed: $($Arguments -join ' ')" }
    return $taskLines
}
function Sort-Ordinal([string[]]$Values) {
    [Array]::Sort($Values, [StringComparer]::Ordinal)
    return $Values
}
function Read-Notice([string]$File) {
    $taskText = [IO.File]::ReadAllText($File).Replace("`r`n", "`n").Replace("`r", "`n")
    if ([string]::IsNullOrWhiteSpace($taskText) -or $taskText.Contains([char]0)) { throw 'Invalid or empty attribution file' }
    # Normalize layout whitespace without changing license wording.
    $taskText = [Text.RegularExpressions.Regex]::Replace($taskText, '[ \t]+(?=\n|$)', '')
    return $taskText.TrimEnd("`n") + "`n"
}
function Get-Notices([string]$Directory) {
    $taskBase = [IO.Path]::GetFullPath($Directory).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
    $taskPaths = [Collections.Generic.List[string]]::new()
    $taskPending = [Collections.Generic.Stack[string]]::new()
    $taskPending.Push($taskBase)
    while ($taskPending.Count -gt 0) {
        foreach ($taskEntry in Get-ChildItem -LiteralPath $taskPending.Pop() -Force) {
            # Never follow links outside checksum-verified module/toolchain source.
            if (($taskEntry.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) { throw 'Linked source entry requires manual review' }
            if ($taskEntry.PSIsContainer) {
                if ($taskEntry.Name -ne '.git') { $taskPending.Push($taskEntry.FullName) }
            } elseif ($taskEntry.Name -match $taskPattern) {
                if (!$taskEntry.FullName.StartsWith($taskBase, [StringComparison]::OrdinalIgnoreCase)) { throw 'Attribution escaped source root' }
                $taskPaths.Add($taskEntry.FullName.Substring($taskBase.Length).Replace('\', '/'))
            }
        }
    }
    return Sort-Ordinal $taskPaths.ToArray()
}
function Add-SourceNotices($Builder, [string]$Directory, [string[]]$Paths) {
    foreach ($taskRelative in $Paths) {
        [void]$Builder.Append("`n--- Source file: $taskRelative ---`n`n")
        [void]$Builder.Append((Read-Notice (Join-Path $Directory $taskRelative)))
    }
}
function Write-Generated([string]$Name, [string]$Content) {
    $taskPath = Join-Path $taskRoot "licenses/$Name"
    if ($Check) {
        if (!(Test-Path -LiteralPath $taskPath) -or [IO.File]::ReadAllText($taskPath) -cne $Content) { throw "Bundled notices out of date: $Name" }
        Write-Output "Verified $Name"
    } else {
        [IO.File]::WriteAllText($taskPath, $Content, $taskUTF8)
        Write-Output "Generated $Name"
    }
}

$taskSavedEnv = @{}
foreach ($taskKey in 'GOOS','GOARCH','CGO_ENABLED','GOTOOLCHAIN','GOTELEMETRY','GOENV','GOWORK') {
    $taskSavedEnv[$taskKey] = [Environment]::GetEnvironmentVariable($taskKey)
}
try {
    $env:GOOS='linux'; $env:GOARCH='amd64'; $env:CGO_ENABLED='0'
    $env:GOTOOLCHAIN='local'; $env:GOTELEMETRY='off'; $env:GOENV='off'; $env:GOWORK='off'
    $taskVersion = (Invoke-Go @('env','GOVERSION')).Trim()
    if ($taskVersion -ne 'go1.27.2') { throw 'Use the pinned Go 1.27.2 toolchain; review notices when upgrading it' }
    $taskGoRoot = (Invoke-Go @('env','GOROOT')).Trim()
    $taskGoNotices = @(Get-Notices $taskGoRoot)
    if ($taskGoNotices -notcontains 'LICENSE' -or $taskGoNotices -notcontains 'PATENTS') { throw 'Go license/patent notices are missing' }
    foreach ($taskTarget in @(
        @{Directory=$taskRoot; Package='./cmd/dockspire'; Name='app-third-party.txt'; Tags=''},
        @{Directory=(Join-Path $taskRoot 'deploy/compose-runtime'); Package='github.com/docker/compose/v5/cmd'; Name='compose-third-party.txt'; Tags='e2e'}
    )) {
        Push-Location $taskTarget.Directory
        try {
            Invoke-Go @('mod','verify') | Out-Null
            $taskTemplate='{{if .Module}}{{.Module.Path}}|{{.Module.Version}}|{{.Module.Dir}}|{{if .Module.Replace}}REPLACED{{end}}{{end}}'
            $taskArgs=@('list','-buildvcs=false','-mod=readonly','-deps',"-tags=$($taskTarget.Tags)",'-f',$taskTemplate,$taskTarget.Package)
            $taskRows = @(Invoke-Go $taskArgs | Where-Object { $_ })
            $taskUnique = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
            foreach ($taskRow in $taskRows) { [void]$taskUnique.Add($taskRow) }
            $taskBuilder=[Text.StringBuilder]::new()
            [void]$taskBuilder.Append("Bundled third-party attribution`nTarget: $($taskTarget.Package)`nPlatform: linux/amd64; CGO disabled; tags: [$($taskTarget.Tags)]`nGo toolchain: $taskVersion`nGenerated by scripts/generate-notices.ps1. Do not edit by hand.`n`nThis is a conservative source-notice superset for modules in the target import graph,`nincluding nested notices. It does not select a license for Dockspire or establish legal clearance.`nReview unfamiliar or restrictive terms before distribution. Module versions and source-file`npaths below form the attribution inventory; preserve the original license terms.`n`n=== Go standard library and bundled source; $taskVersion ===`nSource: https://go.dev/dl/`n")
            Add-SourceNotices $taskBuilder $taskGoRoot $taskGoNotices
            foreach ($taskRow in (Sort-Ordinal @($taskUnique))) {
                $taskParts=$taskRow.Split('|')
                if ($taskParts.Count -ne 4 -or $taskParts[3] -ne '') { throw 'Replaced/unknown dependency source requires manual review' }
                $taskModule,$taskModuleVersion,$taskDirectory=$taskParts[0..2]
                if ($taskModule -eq 'github.com/Mayo-Nas/dockspire' -and $taskModuleVersion -eq '' -and [IO.Path]::GetFullPath($taskDirectory) -eq [IO.Path]::GetFullPath($taskRoot)) { continue }
                if ($taskModuleVersion -notmatch '^v[0-9]' -or !(Test-Path -LiteralPath $taskDirectory -PathType Container)) { throw 'Unknown dependency version/source requires manual review' }
                $taskRootLicense=@(Get-ChildItem -LiteralPath $taskDirectory -File | Where-Object { $_.Name -match '^(LICENSE|LICENCE|COPYING)([.-].*)?$' })
                if ($taskRootLicense.Count -eq 0) { throw "Missing root license for $taskModule" }
                $taskNotices=@(Get-Notices $taskDirectory)
                [void]$taskBuilder.Append("`n=== Module: $taskModule $taskModuleVersion ===`nSource: https://pkg.go.dev/$taskModule@$taskModuleVersion`n")
                Add-SourceNotices $taskBuilder $taskDirectory $taskNotices
            }
            Write-Generated $taskTarget.Name $taskBuilder.ToString()
        } finally { Pop-Location }
    }
} finally {
    foreach ($taskKey in $taskSavedEnv.Keys) { [Environment]::SetEnvironmentVariable($taskKey, $taskSavedEnv[$taskKey]) }
}